def resolve_toctree_slugs(page: Page, all_slugs: set[str]) -> list[str]:
    out: list[str] = []
    for entry in page.toctree:
        entry_clean = entry.replace(".md", "")
        if entry_clean.endswith("/index"):
            entry_clean = entry_clean[: -len("/index")]
        cand = f"{page.slug}/{entry_clean}" if page.slug else entry_clean
        if cand in all_slugs:
            out.append(cand)
    return out


def render_doc_page_tsx(page: Page, all_pages: list[Page]) -> str:
    page_component = f"{pascal(page.slug.split('/')[-1] or 'home')}Page"
    all_slugs = {p.slug for p in all_pages}
    children = resolve_toctree_slugs(page, all_slugs)
    title_by_slug = {p.slug: p.title for p in all_pages}

    lines: list[str] = []
    lines.append(GENERATED_HEADER.format(source=page.source_md))
    lines.append("import React from 'react';")
    lines.append("")
    lines.append(f"export function {page_component}() {{")
    lines.append("  return (")
    lines.append(
        "    <div className=\"mx-auto w-full max-w-3xl flex-1 overflow-y-auto px-6 py-10\">"
    )
    lines.append(
        f"      <h1 className=\"text-2xl font-semibold tracking-tight text-ink\">"
    )
    lines.append(f"        {page.title}")
    lines.append("      </h1>")
    if page.description:
        lines.append(
            "      <p className=\"mt-4 max-w-prose text-base leading-relaxed text-primary-800\">"
        )
        lines.append(f"        {page.description}")
        lines.append("      </p>")
    if children:
        lines.append("      <ul className=\"mt-6 flex flex-col gap-2\">")
        for child_slug in children:
            child_title = title_by_slug.get(child_slug, child_slug)
            lines.append("        <li>")
            lines.append(
                f"          <a href=\"/{child_slug}\" className=\"text-primary-700 hover:underline\">"
            )
            lines.append(f"            {child_title}")
            lines.append("          </a>")
            lines.append("        </li>")
        lines.append("      </ul>")
    lines.append("    </div>")
    lines.append("  );")
    lines.append("}")
    lines.append("")
    lines.append(f"export default {page_component};")
    lines.append("")
    return "\n".join(lines)


