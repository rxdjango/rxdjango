def render_example_page_tsx(page: Page) -> str:
    assert page.rxdemo is not None
    app = page.rxdemo
    pascal_name = pascal(page.slug.split("/")[-1])
    kebab_slug = kebab(page.slug)
    demo_component = f"{pascal(app)}Demo"
    page_component = f"{pascal_name}Page"

    needs_badge = any(s.is_frontend for s in page.sections)

    imports_layout = [
        "ExampleLayout",
        "ExampleSection",
        "ExampleSectionHeading",
        "ExampleDescription",
    ]
    if needs_badge:
        imports_layout.append("ExampleClientBadge")

    lines: list[str] = []
    lines.append(GENERATED_HEADER.format(source=page.source_md))
    lines.append("import React from 'react';")
    lines.append(f"import {{ {demo_component} }} from './demo';")
    lines.append("import {")
    for name in imports_layout:
        lines.append(f"  {name},")
    lines.append("} from '../../components/ExampleLayout';")
    lines.append("import { SourceFile } from '../../components/SourceFile';")
    lines.append("")
    lines.append(f"export function {page_component}() {{")
    lines.append("  return (")
    lines.append(
        f"    <ExampleLayout title=\"{page.title}\" demo={{<{demo_component} />}}>"
    )

    lines.append('      <ExampleSection position="first">')
    lines.append("        <ExampleDescription>")
    lines.append(f"          {page.description}")
    lines.append("        </ExampleDescription>")
    lines.append("      </ExampleSection>")

    last_index = len(page.sections) - 1
    for idx, section in enumerate(page.sections):
        section_id = f"{kebab_slug}-{section.name.lower().replace(' ', '-')}"
        attrs = [f'ariaLabelledBy="{section_id}"']
        if idx == last_index:
            attrs.append('position="last"')
        attrs_str = " ".join(attrs)
        lines.append(f"      <ExampleSection {attrs_str}>")

        if section.is_frontend:
            lines.append(
                "        <div className=\"flex flex-col gap-3 sm:flex-row sm:items-end sm:justify-between\">"
            )
            lines.append(
                f"          <ExampleSectionHeading id=\"{section_id}\">"
            )
            lines.append(f"            {section.name}")
            lines.append("          </ExampleSectionHeading>")
            lines.append("          <ExampleClientBadge />")
            lines.append("        </div>")
        else:
            lines.append(f"        <ExampleSectionHeading id=\"{section_id}\">")
            lines.append(f"          {section.name}")
            lines.append("        </ExampleSectionHeading>")

        lines.append(f"        <SourceFile path=\"{section.source_path}\" />")
        lines.append("      </ExampleSection>")

    lines.append("    </ExampleLayout>")
    lines.append("  );")
    lines.append("}")
    lines.append("")
    lines.append(f"export default {page_component};")
    lines.append("")
    return "\n".join(lines)


