def example_page_path(page: Page) -> Path:
    # app/examples/<app>/<Pascal>Page.tsx
    assert page.rxdemo is not None
    pascal_name = pascal(page.slug.split("/")[-1])
    return EXAMPLES_OUT / page.rxdemo / f"{pascal_name}Page.tsx"


def doc_page_path(page: Page) -> Path:
    # app/pages/<slug>/Page.tsx
    return PAGES_OUT / page.slug / "Page.tsx"


def import_specifier(target: Path) -> str:
    rel = target.relative_to(FRONTEND_APP).with_suffix("")
    return "./" + str(rel)


def pascal_alias(page: Page) -> str:
    # Unique alias for non-demo page imports based on full slug.
    return pascal(page.slug.replace("/", "_")) + "Page"


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------


def write_if_changed(path: Path, content: str) -> bool:
    if path.exists() and path.read_text(encoding="utf-8") == content:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    return True


def render_registry_ts(pages: list[Page]) -> str:
    lines: list[str] = []
    lines.append("// @generated by tools/docgen — do not edit.")
    lines.append("// Source: docs/")
    lines.append("import type { ReactElement } from 'react';")

    for page in pages:
        alias = pascal_alias(page)
        if page.rxdemo:
            local = f"{pascal(page.slug.split('/')[-1])}Page"
            lines.append(
                f"import {{ {local} as {alias} }} from '{import_specifier(example_page_path(page))}';"
            )
            lines.append(
                f"import {{ {pascal(page.rxdemo)}Demo }} from './examples/{page.rxdemo}/demo';"
            )
        else:
            local = f"{pascal(page.slug.split('/')[-1] or 'home')}Page"
            lines.append(
                f"import {{ {local} as {alias} }} from '{import_specifier(doc_page_path(page))}';"
            )
    lines.append("")
    lines.append("export type Page = {")
    lines.append("  slug: string;")
    lines.append("  title: string;")
    lines.append("  depth: number;")
    lines.append("  parent: string | null;")
    lines.append("  Component: () => ReactElement;")
    lines.append("  Demo: (() => ReactElement) | null;")
    lines.append("};")
    lines.append("")
    lines.append("export const pages: Page[] = [")
    for page in pages:
        parent_repr = "null" if page.parent is None else f"'{js_string(page.parent)}'"
        component = pascal_alias(page)
        demo = f"{pascal(page.rxdemo)}Demo" if page.rxdemo else "null"
        lines.append(
            "  { "
            f"slug: '{js_string(page.slug)}', "
            f"title: '{js_string(page.title)}', "
            f"depth: {page.depth}, "
            f"parent: {parent_repr}, "
            f"Component: {component}, "
            f"Demo: {demo}"
            " },"
        )
    lines.append("];")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    raw_pages = discover_pages()
    pages = order_pages(raw_pages)

    written = 0
    for page in pages:
        if page.rxdemo:
            target = example_page_path(page)
            content = render_example_page_tsx(page)
        else:
            target = doc_page_path(page)
            content = render_doc_page_tsx(page, pages)
        if write_if_changed(target, content):
            written += 1
            print(f"wrote {target.relative_to(REPO_ROOT)}")

    if write_if_changed(REGISTRY_OUT, render_registry_ts(pages)):
        written += 1
        print(f"wrote {REGISTRY_OUT.relative_to(REPO_ROOT)}")

    print(f"docgen: {len(pages)} page(s), {written} file(s) updated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
